function bodyFromSections(sections) {
  return sections.map(([h, p]) => `## ${h}\n\n${p}\n`).join('\n');
}

function pad2(n) {
  return String(n).padStart(2, '0');
}

let i = 0;
for (const item of items) {
  const authorSlug = authors[i % authors.length];
  const category = categories[i] ?? 'news';
  const month = 3 - Math.floor(i / 11);
  const day = 28 - (i % 27);
  const date = `2026-${pad2(Math.max(1, month))}-${pad2(day)}`;
  const image = `${item.num}-${item.slug}.webp`;
  const fm = {
    title: item.title,
    subtitle: item.subtitle,
    author: authorNames[authorSlug],
    author_slug: authorSlug,
    date,
    category,
    tags: item.tags,
    source_name: item.source_name,
    source_url: item.source_url,
    source_published_at: '2026-02-01',
    excerpt: item.excerpt,
    image,
    image_alt: item.title.slice(0, 120),
    featured: i === 10,
    popular: i === 4 || i === 22,
    verified: true,
  };

  const lines = ['---'];
  for (const [k, v] of Object.entries(fm)) {
    if (typeof v === 'string') lines.push(`${k}: '${v.replace(/'/g, "''")}'`);
    else if (typeof v === 'boolean') lines.push(`${k}: ${v}`);
    else if (Array.isArray(v)) lines.push(`${k}: [${v.map((t) => `'${t.replace(/'/g, "''")}'`).join(', ')}]`);
  }
  lines.push('---', '', bodyFromSections(item.sections), '');

  const filename = `${item.num}-${item.slug}.md`;
  fs.writeFileSync(path.join(newsDir, filename), lines.join('\n'), 'utf8');
  console.log('Wrote', filename);
  i++;
}
